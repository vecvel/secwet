// Flutter outputs of the brand package, from the same sources as desktop:
//   apps/mobile/lib/theme/brand_mark.g.dart    Splash Twin mark paths (geometry.mjs)
//   apps/mobile/lib/theme/secwet_icons.g.dart  outline icon set (apps/desktop/src/components/Icon.tsx)
// Run on its own with `node packages/brand/flutter.mjs`; build.mjs also calls it.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { twin } from "./geometry.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const SMALL_MAX = 32; // keep in step with build.mjs

const dartString = (s) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$")}'`;
const num = (v) => {
  const n = Number(v);
  if (!Number.isFinite(n)) throw new Error(`not a number: ${v}`);
  return Number.isInteger(n) ? `${n}.0` : String(n);
};

function write(rel, text) {
  const p = resolve(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
}

/** Parses the `paths` table of Icon.tsx into {name: [{tag, attrs}]}. */
export function parseIcons(source) {
  const start = source.indexOf("const paths = {");
  const end = source.indexOf("} satisfies");
  if (start < 0 || end < 0) throw new Error("Icon.tsx: paths table not found");
  const table = source.slice(start, end);
  const entries = [...table.matchAll(/^ {2}([A-Za-z][A-Za-z0-9]*): /gm)];
  const icons = {};
  entries.forEach((m, i) => {
    const body = table.slice(m.index, i + 1 < entries.length ? entries[i + 1].index : undefined);
    const shapes = [...body.matchAll(/<(path|rect|circle)\b([^>]*?)\/>/g)].map(([, tag, rawAttrs]) => {
      const attrs = {};
      for (const [, key, quoted, braced] of rawAttrs.matchAll(/([A-Za-z]+)=(?:"([^"]*)"|\{([^}]*)\})/g)) {
        attrs[key] = quoted ?? braced;
      }
      return { tag, attrs };
    });
    if (shapes.length === 0) throw new Error(`Icon.tsx: icon ${m[1]} has no shapes`);
    icons[m[1]] = shapes;
  });
  return icons;
}

function dartShape({ tag, attrs }) {
  const filled = attrs.fill === "currentColor" ? ", filled: true" : "";
  const stroke = attrs.strokeWidth ? `, strokeWidth: ${num(attrs.strokeWidth)}` : "";
  switch (tag) {
    case "path":
      return `IconPath(${dartString(attrs.d)}${stroke}${filled})`;
    case "rect":
      return `IconRect(${num(attrs.x ?? 0)}, ${num(attrs.y ?? 0)}, ${num(attrs.width)}, ${num(attrs.height)}, ${num(attrs.rx ?? 0)}${stroke}${filled})`;
    case "circle":
      return `IconCircle(${num(attrs.cx)}, ${num(attrs.cy)}, ${num(attrs.r)}${stroke}${filled})`;
    default:
      throw new Error(`unsupported shape ${tag}`);
  }
}

export function writeFlutter() {
  // 1. Brand mark
  const big = twin();
  const small = twin({ small: true });
  write(
    "apps/mobile/lib/theme/brand_mark.g.dart",
    `// Generated by packages/brand/flutter.mjs from packages/brand/geometry.mjs. Do not edit by hand.

/// Splash Twin mark paths in a 40 x 40 box with origin (12, 12), like the desktop BrandMark.
abstract final class BrandMarkPaths {
  static const double backOpacity = ${num(big.backOpacity)};
  static const double smallMaxPx = ${num(SMALL_MAX)};
  static const String largeBack = ${dartString(big.back)};
  static const String largeFront = ${dartString(big.front)};
  static const String smallBack = ${dartString(small.back)};
  static const String smallFront = ${dartString(small.front)};
}
`,
  );

  // 2. Icon set
  const icons = parseIcons(readFileSync(resolve(root, "apps/desktop/src/components/Icon.tsx"), "utf8"));
  const names = Object.keys(icons);
  write(
    "apps/mobile/lib/theme/secwet_icons.g.dart",
    `// Generated by packages/brand/flutter.mjs from apps/desktop/src/components/Icon.tsx. Do not edit by hand.
import 'icon_shapes.dart';

/// The desktop outline icon set: 20 pt grid, 1.5 stroke, round caps and joins.
enum SecwetIcons { ${names.join(", ")} }

const Map<SecwetIcons, List<IconShape>> secwetIconShapes = {
${names.map((n) => `  SecwetIcons.${n}: [\n${icons[n].map((s) => `    ${dartShape(s)},`).join("\n")}\n  ],`).join("\n")}
};
`,
  );
  console.log(`brand: wrote Flutter brand mark and ${names.length} icons`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) writeFlutter();
