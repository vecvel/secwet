// Generates platform outputs from tokens.json:
//   dist/tokens.css                       (desktop webview, CSS custom properties)
//   apps/mobile/lib/theme/secwet_tokens.dart (Flutter constants)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(resolve(here, "tokens.json"), "utf8"));

const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const px = (n) => `${n}px`;

function scaleVars(prefix, obj, unit = px) {
  return Object.entries(obj).map(([k, v]) => `  --${prefix}-${kebab(k)}: ${unit(v)};`);
}
function colorVars(mode) {
  return Object.entries(t.color[mode]).map(([k, v]) => `  --color-${kebab(k)}: ${v};`);
}

const statics = [
  `  --font-sans: ${t.font.sans};`,
  ...scaleVars("font-size", t.fontSize),
  ...scaleVars("font-weight", t.fontWeight, String),
  ...scaleVars("line-height", t.lineHeight, String),
  ...scaleVars("space", t.space),
  ...scaleVars("radius", t.radius),
  ...scaleVars("control", t.control),
  ...scaleVars("layout", t.layout),
  `  --shadow-overlay: ${t.shadow.overlay};`,
  ...scaleVars("duration", t.duration, (v) => `${v}ms`),
];

const css = `/* Generated by packages/design-tokens/build.mjs. Do not edit by hand. */
/* Breakpoints: compact < ${t.breakpoint.compact}px <= medium < ${t.breakpoint.medium}px <= expanded */
:root {
${statics.join("\n")}
${colorVars("light").join("\n")}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars("dark").map((l) => "  " + l).join("\n")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${colorVars("dark").join("\n")}
  color-scheme: dark;
}
`;

mkdirSync(resolve(here, "dist"), { recursive: true });
writeFileSync(resolve(here, "dist/tokens.css"), css);

// Flutter: colors as Color(0xAARRGGBB), numbers as doubles.
function dartColor(v) {
  if (v.startsWith("#")) return `Color(0xFF${v.slice(1).toUpperCase()})`;
  const [r, g, b, a] = v.match(/[\d.]+/g).map(Number);
  const hex = (n) => n.toString(16).padStart(2, "0").toUpperCase();
  return `Color(0x${hex(Math.round(a * 255))}${hex(r)}${hex(g)}${hex(b)})`;
}
function dartPalette(mode) {
  return Object.entries(t.color[mode]).map(([k, v]) => `    ${k}: ${dartColor(v)},`).join("\n");
}
function dartNumbers(cls, obj) {
  const fields = Object.entries(obj)
    .map(([k, v]) => `  static const double ${/^\d/.test(k) ? "s" + k : k} = ${Number(v).toFixed(1)};`)
    .join("\n");
  return `abstract final class ${cls} {\n${fields}\n}`;
}

const dart = `// Generated by packages/design-tokens/build.mjs. Do not edit by hand.
import 'package:flutter/widgets.dart';

class SecwetPalette {
  const SecwetPalette({
${Object.keys(t.color.light).map((k) => `    required this.${k},`).join("\n")}
  });

${Object.keys(t.color.light).map((k) => `  final Color ${k};`).join("\n")}

  static const light = SecwetPalette(
${dartPalette("light")}
  );

  static const dark = SecwetPalette(
${dartPalette("dark")}
  );
}

${dartNumbers("SecwetFontSize", t.fontSize)}

${dartNumbers("SecwetSpace", t.space)}

${dartNumbers("SecwetRadius", t.radius)}

${dartNumbers("SecwetControl", t.control)}

${dartNumbers("SecwetBreakpoint", t.breakpoint)}
`;

const dartOut = resolve(here, "../../apps/mobile/lib/theme/secwet_tokens.dart");
mkdirSync(dirname(dartOut), { recursive: true });
writeFileSync(dartOut, dart);

console.log("tokens: wrote dist/tokens.css and apps/mobile/lib/theme/secwet_tokens.dart");
