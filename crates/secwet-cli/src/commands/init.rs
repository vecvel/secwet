//! Project configuration generator (.secwet.toml) for secwet-cli.

use crate::config::SecwetConfig;
use crate::resolver::resolve_item;
use clap::Args;
use secwet_core::{Error, Result, Secwet};
use std::path::Path;

#[derive(Args, Debug)]
pub struct InitArgs {
    /// Item name or UUID to link this repository to
    #[arg(short = 'i', long = "item", visible_alias = "project")]
    pub item: Option<String>,

    /// Default environment name to use (e.g. development)
    #[arg(short = 'e', long = "env")]
    pub env: Option<String>,

    /// Overwrite existing .secwet.toml if present
    #[arg(long)]
    pub force: bool,
}

pub fn execute_init(
    secwet: &Secwet,
    args: InitArgs,
    config: Option<&SecwetConfig>,
) -> Result<()> {
    let config_path = Path::new(".secwet.toml");
    if config_path.exists() && !args.force {
        eprintln!("error: .secwet.toml already exists in current directory (use --force to overwrite)");
        return Err(Error::Invalid {
            field: "config",
            message: "file already exists".into(),
        });
    }

    let item = resolve_item(secwet, args.item.as_deref(), config)?;
    let env_str = args
        .env
        .or_else(|| item.environments.first().map(|e| e.name.clone()))
        .unwrap_or_else(|| "development".to_string());

    let content = format!(
        "# Secwet Project Configuration\n# Generated by `secwet init`\n\nitem = \"{}\"\nenvironment = \"{}\"\n",
        item.name, env_str
    );

    std::fs::write(config_path, content).map_err(|_| Error::Storage)?;
    println!(
        "Initialized .secwet.toml linked to item '{}' with environment '{}'",
        item.name, env_str
    );
    Ok(())
}

